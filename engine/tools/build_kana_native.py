"""engine/data/ja-kana-native.txt: Japanese words usually written in kana (この, あなた, ちょっと).

Counted on Tatoeba's Japanese sentences (CC BY 2.0 FR; ~/Projects/jis-moonshot/corpora/
jpn_sentences.tsv.bz2), the robot's test sentences (engine/tests/data/robot/ja-tatoeba.tsv) left out.
Each word (a SudachiPy token: SudachiDict core, Apache-2.0) is counted under its reading; a reading
is kana-native when it's written in hiragana at least SHARE of the time, in at least MIN_COUNT
sentences. Particles and auxiliaries are left out (they're kana anyway).

    tools/analysis/.venv/bin/python engine/tools/build_kana_native.py

Output: reading, tab, times seen, tab, share written in kana; most frequent first.

Also engine/data/ja-common-words.txt: the COMMON most common words not written in kana (content
words in their dictionary form: 死, 一, 原因, ケン), as surface, tab, reading, tab, times seen. The
engine raises them in the menu when the whole reading is typed (docs/spec.md §11.2).
"""
import bz2, collections, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.expanduser("~/Projects/jis-moonshot/corpora/jpn_sentences.tsv.bz2")
HELD_OUT = os.path.join(HERE, "..", "tests", "data", "robot", "ja-tatoeba.tsv")
OUT = os.path.join(HERE, "..", "data", "ja-kana-native.txt")
OUT_COMMON = os.path.join(HERE, "..", "data", "ja-common-words.txt")
COMMON = 3000
# Readings SudachiDict gets wrong for everyday typing.
READING_FIX = {"私": "わたし"}
MIN_COUNT = 8
SHARE = 0.6
# Readings the count gets wrong: SudachiDict reads 私 as わたくし, so わたし only ever counts as kana.
EXCLUDE = {"わたし"}
SKIP_POS = {"助詞", "助動詞", "補助記号", "空白", "記号"}


def hira(kata):
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in kata)


def main():
    from sudachipy import Dictionary, SplitMode
    tok = Dictionary(dict="core").tokenizer()
    # The robot's phrases come from these sentences: leave out every sentence holding one of them
    # in a row (the phrases of one sentence are consecutive lines).
    held = [l.split("\t")[0] for l in open(HELD_OUT, encoding="utf-8") if not l.startswith("#")]
    held_out = set()
    for i in range(0, len(held) - 2):
        held_out.add("".join(held[i:i + 3]))
    total, kana = collections.Counter(), collections.Counter()
    spelled = collections.Counter()
    n = skipped = 0
    for line in bz2.open(SRC, "rt", encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 3:
            continue
        s = parts[2]
        plain = re.sub(r"[、。！？「」\s]", "", s)
        if any(h in plain for h in held_out):
            skipped += 1
            continue
        n += 1
        seen = set()
        for m in tok.tokenize(s, SplitMode.C):
            if m.part_of_speech()[0] in SKIP_POS:
                continue
            reading = READING_FIX.get(m.surface(), hira(m.reading_form()))
            if m.surface() != reading and m.surface() == m.dictionary_form() and m.part_of_speech()[0] != "接頭辞" \
                    and re.fullmatch(r"[ぁ-んー]+", reading) and not re.search(r"[0-9０-９A-Za-zＡ-Ｚａ-ｚ]", m.surface()) \
                    and (m.surface(), reading, "w") not in seen:
                seen.add((m.surface(), reading, "w"))
                spelled[(m.surface(), reading)] += 1
            if not re.fullmatch(r"[ぁ-ゖー]{2,8}", reading) or (reading, m.surface()) in seen:
                continue
            seen.add((reading, m.surface()))
            total[reading] += 1
            if m.surface() == reading:
                kana[reading] += 1
    words = [(r, c, kana[r] / c) for r, c in total.items() if c >= MIN_COUNT and kana[r] / c >= SHARE and r not in EXCLUDE]
    words.sort(key=lambda w: (-w[1], w[0]))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# Japanese words usually written in kana: reading, times seen, share written in kana. From Tatoeba\n")
        f.write("# Japanese sentences (CC BY 2.0 FR), readings by SudachiDict core (Apache-2.0). Generated by\n")
        f.write("# tools/build_kana_native.py; see LICENSE-corpora.txt.\n")
        for r, c, share in words:
            f.write(f"{r}\t{c}\t{share:.2f}\n")
    with open(OUT_COMMON, "w", encoding="utf-8") as f:
        f.write("# The most common Japanese words not written in kana: surface, reading, times seen. From Tatoeba\n")
        f.write("# Japanese sentences (CC BY 2.0 FR), readings by SudachiDict core (Apache-2.0). Generated by\n")
        f.write("# tools/build_kana_native.py; see LICENSE-corpora.txt.\n")
        for (w, r), c in sorted(spelled.items(), key=lambda x: (-x[1], x[0]))[:COMMON]:
            f.write(f"{w}\t{r}\t{c}\n")
    print(f"{n} sentences ({skipped} held out): {len(words)} kana-native words")


if __name__ == "__main__":
    main()
